    def refresh_owners(self):
        """
        Reloads the Registered Owners table from Pluto's real database:
            GET /owners  ->  OwnerManager.list_owners()  ->  pluto.db
        This is the single source of truth for registered owners -- there
        is no local owners.json anymore. If Pluto isn't reachable yet, the
        table is simply left as-is (or empty on first load).
        """
        for item in self.tree.get_children():
            self.tree.delete(item)

        if not (self.robot and self.robot.api):
            return

        try:
            result = self.robot.api.list_owners()
        except PlutoAPIClientError:
            return

        owners = result.get("owners", []) if isinstance(result, dict) else []
        # newest first, matching registered_at (ISO, sortable as string)
        for record in sorted(owners, key=lambda r: r.get("registered_at", ""), reverse=True):
            registered_at = record.get("registered_at", "")
            # server stores ISO 'YYYY-MM-DDTHH:MM:SS'; show just the date part
            registered_display = registered_at.split("T")[0] if registered_at else ""
            self.tree.insert("", "end", values=(
                record.get("name", ""),
                record.get("dob", ""),
                "\u2713" if record.get("face_files") else "\u2717",
                "\u2713" if record.get("voice_files") else "\u2717",
                registered_display,
            ))

