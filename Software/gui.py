def rounded_rect_points(x1, y1, x2, y2, r):
    r = min(r, (x2 - x1) / 2, (y2 - y1) / 2)
    return [
        x1 + r, y1, x2 - r, y1, x2, y1, x2, y1 + r,
        x2, y2 - r, x2, y2, x2 - r, y2, x1 + r, y2,
        x1, y2, x1, y2 - r, x1, y1 + r, x1, y1,
    ]


def draw_rounded_rect(canvas, x1, y1, x2, y2, r=14, **kwargs):
    return canvas.create_polygon(rounded_rect_points(x1, y1, x2, y2, r), smooth=True, **kwargs)


def draw_gradient_strip(canvas, x1, y1, x2, y2, c1, c2, steps=60):
    width = (x2 - x1) / steps
    for i in range(steps):
        t = i / (steps - 1)
        color = mix(c1, c2, t)
        canvas.create_rectangle(x1 + i * width, y1, x1 + (i + 1) * width + 1, y2,
                                 fill=color, outline=color)


