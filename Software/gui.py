class RobotDashboardApp(tk.Tk):
    def __init__(self):
        super().__init__()
        self.title("Pluto Control Dashboard")
        self.geometry("1280x800")
        self.minsize(1020, 660)
        self.configure(bg=Theme.BG)

        self.robot = RobotCore()

        self._setup_style()
        self._build_sidebar()
        self.right_container = tk.Frame(self, bg=Theme.BG)
        self.right_container.pack(side="right", fill="both", expand=True)
        self._build_content()

        self.protocol("WM_DELETE_WINDOW", self._on_close)

    def _setup_style(self):
        style = ttk.Style(self)
        try:
            style.theme_use("clam")
        except tk.TclError:
            pass
        style.configure("TCombobox", fieldbackground=Theme.TRACK, background=Theme.TRACK,
                         foreground=Theme.TEXT_MAIN, arrowcolor=Theme.TEXT_SUB)

    def _build_sidebar(self):
        self.sidebar = tk.Frame(self, bg=Theme.BG_SIDEBAR, width=210)
        self.sidebar.pack(side="left", fill="y")
        self.sidebar.pack_propagate(False)

        brand = tk.Frame(self.sidebar, bg=Theme.BG_SIDEBAR)
        brand.pack(fill="x", pady=(28, 26))
        logo_canvas = tk.Canvas(brand, width=56, height=56, bg=Theme.BG_SIDEBAR, highlightthickness=0)
        logo_canvas.pack()
        icon_robot_head(logo_canvas, 28, 30, 44, Theme.ACCENT)
        tk.Label(brand, text="PLUTO", font=(Theme.FONT, 13, "bold"), bg=Theme.BG_SIDEBAR,
                 fg=Theme.TEXT_MAIN).pack(pady=(10, 0))
        

        tk.Frame(self.sidebar, bg=Theme.BORDER, height=1).pack(fill="x", padx=18, pady=(0, 16))

        self.nav_buttons = {}
        self.nav_indicators = {}
        nav_items = [("dashboard", "Dashboard"), ("memory", "Memory Core"),
                     ("owners", "Register Owner")]
        for key, label in nav_items:
            row = tk.Frame(self.sidebar, bg=Theme.BG_SIDEBAR, cursor="hand2")
            row.pack(fill="x", padx=10, pady=3)
            indicator = tk.Frame(row, bg=Theme.BG_SIDEBAR, width=3)
            indicator.pack(side="left", fill="y")
            lbl = tk.Label(row, text=label, anchor="w", font=(Theme.FONT, 11), bg=Theme.BG_SIDEBAR,
                           fg=Theme.TEXT_SUB, padx=14, pady=10)
            lbl.pack(side="left", fill="x", expand=True)
            for widget in (row, lbl):
                widget.bind("<Button-1>", lambda e, k=key: self.show_frame(k))
                widget.bind("<Enter>", lambda e, k=key: self._hover_nav(k, True))
                widget.bind("<Leave>", lambda e, k=key: self._hover_nav(k, False))
            self.nav_buttons[key] = (row, lbl)
            self.nav_indicators[key] = indicator

        tk.Frame(self.sidebar, bg=Theme.BG_SIDEBAR).pack(fill="both", expand=True)

        connect_btn = tk.Button(self.sidebar, text="\u26a1  Connect to Pluto Core",
                                 anchor="center", relief="flat", font=(Theme.FONT, 10, "bold"),
                                 bg=Theme.ACCENT, fg="#052622", activebackground=Theme.ACCENT_2,
                                 bd=0, padx=14, pady=11, cursor="hand2", command=self.attempt_connect)
        connect_btn.pack(fill="x", padx=14, pady=(2, 18), side="bottom")
        connect_btn.bind("<Enter>", lambda e: connect_btn.config(bg=Theme.ACCENT_2, fg="#ffffff"))
        connect_btn.bind("<Leave>", lambda e: connect_btn.config(bg=Theme.ACCENT, fg="#052622"))

    def _hover_nav(self, key, entering):
        row, lbl = self.nav_buttons[key]
        if self._current_frame == key:
            return
        color = "#161d27" if entering else Theme.BG_SIDEBAR
        row.config(bg=color)
        lbl.config(bg=color)

    def _build_content(self):
        self.pages_container = tk.Frame(self.right_container, bg=Theme.BG)
        self.pages_container.pack(fill="both", expand=True)

        self.frames = {
            "dashboard": DashboardFrame(self.pages_container, self.robot),
            "memory": MemoryCoreFrame(self.pages_container, self.robot),
            "owners": OwnerRegistrationFrame(self.pages_container, self.robot),
        }
        for frame in self.frames.values():
            frame.place(relx=0, rely=0, relwidth=1, relheight=1)

        self._current_frame = None
        self.show_frame("dashboard")

    def show_frame(self, key):
        self._current_frame = key
        self.frames[key].tkraise()
        for k, (row, lbl) in self.nav_buttons.items():
            active = k == key
            bg = Theme.ACCENT_DIM if active else Theme.BG_SIDEBAR
            fg = Theme.ACCENT if active else Theme.TEXT_SUB
            row.config(bg=bg)
            lbl.config(bg=bg, fg=fg)
            self.nav_indicators[k].config(bg=Theme.ACCENT if active else Theme.BG_SIDEBAR)

    def attempt_connect(self):
        """Connects to Pluto: checks the FastAPI health endpoint and starts
        the telemetry + camera WebSocket clients (which keep retrying in
        the background even if Pluto isn't reachable yet)."""
        if PlutoAPIClient is None:
            messagebox.showerror(
                "API Client Unavailable",
                f"api_client.py could not be imported.\n\nDetails: {API_CLIENT_ERROR}\n\n"
                "Install it with:\n    pip install requests"
            )
            return
        if PlutoWebSocketClient is None or PlutoVideoClient is None:
            messagebox.showerror(
                "WebSocket Client Unavailable",
                "websocket_client.py / video_client.py could not be imported.\n\n"
                f"Details: {WS_CLIENT_ERROR or VIDEO_CLIENT_ERROR}\n\n"
                "Install it with:\n    pip install websocket-client pillow"
            )
            return

        ok = self.robot.connect()
        if ok:
            messagebox.showinfo(
                "Connected",
                f"Connected to Pluto's FastAPI server at "
                f"{self.robot.host}:{self.robot.api_port}.\n\n"
                f"Telemetry and camera WebSocket clients are now running and "
                f"will keep reconnecting automatically if the link drops."
            )
        else:
            messagebox.showwarning(
                "Cannot Reach Pluto",
                f"Could not reach Pluto's FastAPI server at "
                f"{self.robot.host}:{self.robot.api_port}.\n\n"
                "Make sure Pluto is powered on, server.py is running, and "
                "this device is on the same network. The telemetry/camera "
                "clients will keep retrying in the background and will pick "
                "up automatically once Pluto comes online."
            )

    def _on_close(self):
        self.robot.disconnect()
        self.destroy()


if __name__ == "__main__":
    app = RobotDashboardApp()
