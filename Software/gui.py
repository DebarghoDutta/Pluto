def level_color(value, invert=False):
    """value 0-100 -> color. invert=True means 'high value is bad' (e.g. usage)."""
    if invert:
        if value >= 80:
            return Theme.BAD
        if value >= 55:
            return Theme.WARN
        return Theme.GOOD
    else:
        if value <= 20:
            return Theme.BAD
        if value <= 45:
            return Theme.WARN
        return Theme.GOOD


def mix(hex1, hex2, t):
    """Linearly blend two hex colors, t in [0,1]."""
    r1, g1, b1 = int(hex1[1:3], 16), int(hex1[3:5], 16), int(hex1[5:7], 16)
    r2, g2, b2 = int(hex2[1:3], 16), int(hex2[3:5], 16), int(hex2[5:7], 16)
    r = round(r1 + (r2 - r1) * t)
    g = round(g1 + (g2 - g1) * t)
    b = round(b1 + (b2 - b1) * t)
    return f"#{r:02x}{g:02x}{b:02x}"


