class RoundedCard(tk.Frame):
    """A card with a soft shadow and rounded corners, hosting an inner
    tk.Frame (self.body) where real content should be packed/gridded."""

    def __init__(self, parent, radius=16, bg=Theme.CARD, border=Theme.BORDER, pad=0,
                 width=None, height=None):
        super().__init__(parent, bg=parent["bg"])
        self.radius = radius
        self.card_bg = bg
        self.border = border
        canvas_kwargs = {}
        if width is not None:
            canvas_kwargs["width"] = width
        if height is not None:
            canvas_kwargs["height"] = height
        self.canvas = tk.Canvas(self, bg=parent["bg"], highlightthickness=0, bd=0, **canvas_kwargs)
        self.canvas.pack(fill="both", expand=True)
        self.body = tk.Frame(self.canvas, bg=bg)
        self._win = self.canvas.create_window(4, 4, window=self.body, anchor="nw")
        self.canvas.bind("<Configure>", self._redraw)

    def _redraw(self, event):
        w, h = event.width, event.height
        self.canvas.delete("bg")
        # soft shadow (offset, darker)
        draw_rounded_rect(self.canvas, 3, 5, w - 1, h - 1, self.radius,
                           fill=Theme.CARD_SHADOW, outline="", tags="bg")
        # main card
        draw_rounded_rect(self.canvas, 0, 0, w - 4, h - 4, self.radius,
                           fill=self.card_bg, outline=self.border, width=1, tags="bg")
        self.canvas.tag_lower("bg")
        self.canvas.itemconfig(self._win, width=w - 12, height=h - 14)
        self.canvas.coords(self._win, 6, 6)


