    def _redraw_bar(self):
        c = self.bar_canvas
        w = c.winfo_width()
        h = c.winfo_height()
        if w < 4 or h < 2:
            return
        c.delete("all")
        c.create_rectangle(0, 0, w, h, fill=Theme.TRACK, outline="")
        fill_w = max(3, w * (self._pct / 100))
        c.create_rectangle(0, 0, fill_w, h, fill=self.accent, outline="")

    def set_data(self, data):
        self._data = data
        self.title_label.config(text=data["title"].upper())
        self.purpose_label.config(text=data.get("short_desc", data["purpose"]))

        used = data["used_mb"]
        total = data["total_mb"]
        pct = min(100, (used / total) * 100) if total else 0
        self._pct = pct
        self._redraw_bar()
        self.pct_label.config(text=f"{pct:.0f}%")
        self.storage_label.config(
            text=f"{used:.2f} MB used of {total} MB allocated")

        entries = data["entries"]
        self.entries_title.config(text=f"STORED ENTRIES ({len(entries)})")

        self.text.config(state="normal")
        self.text.delete("1.0", "end")
        for i, (title, detail, ts) in enumerate(entries):
            self.text.insert("end", f"\u2022 {title}\n", "entry_title")
            self.text.insert("end", f"   {detail}\n", "entry_detail")
            self.text.insert("end", f"   {ts}\n", "entry_ts")
            if i < len(entries) - 1:
                self.text.insert("end", "\n")
        self.text.config(state="disabled")


