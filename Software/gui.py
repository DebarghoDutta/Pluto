def _to_iso_dob(dob_str):
    """
    Converts the GUI's 'DD-MM-YYYY' dob string (built from the day/month/year
    comboboxes in OwnerRegistrationFrame) into the 'YYYY-MM-DD' format
    owner_manager.py's validation expects. Returns "" if it can't be parsed
    (owner_manager treats an empty dob as optional).
    """
    try:
        day, month, year = dob_str.split("-")
        return f"{year}-{int(month):02d}-{int(day):02d}"
    except (ValueError, AttributeError):
        return ""


# ============================================================================
#  ROBOT CORE  (mock backend -- the ONLY place that needs to change later)
# ============================================================================
class RobotCore:
    """
    Real interface between the GUI and Pluto (Raspberry Pi 5).

    - api_client.PlutoAPIClient   : FastAPI REST calls (Software -> Pluto):
                                    owner registration, memory reads, commands.
    - websocket_client...Client   : persistent WebSocket (Pluto -> Software):
                                    telemetry (battery/cpu/ram/temp/env/activity).
    - video_client.PlutoVideoClient: persistent WebSocket (Pluto -> Software):
                                    live camera frames.

    All getters below read from a locally cached snapshot that is updated
    by the WebSocket callbacks in the background. Until Pluto is reachable,
    getters return safe "no data yet" placeholders instead of random values.
    """

    # Default snapshot before any telemetry has arrived / while offline.
    _EMPTY_TELEMETRY = {
        "battery_percent": None,
        "connectivity": {"type": "Offline", "state": "No Signal", "kind": "bad"},
        "memory_percent": None,
        "cpu_percent": None,
        "cpu_temp_c": None,
        "ambient_temperature_c": None,
        "humidity_percent": None,
        "light_intensity_lux": None,
        "air_quality_index": None,
        "current_activity": "Disconnected",
    }

    _EMPTY_MEMORY_CARD = {
        "title": "", "short_desc": "No data \u2014 connect to Pluto to load this.",
        "purpose": "", "used_mb": 0, "total_mb": 0, "entries": [],
    }

    def __init__(self):
        self.connected = False
        self.host = ROBOT_HOST
        self.api_port = ROBOT_API_PORT
        self.ws_port = ROBOT_WS_PORT

        self._telemetry_lock = threading.Lock()
        self._telemetry = dict(self._EMPTY_TELEMETRY)

        self._frame_lock = threading.Lock()
        self._latest_frame = None  # PIL.Image or None

        self.api = PlutoAPIClient(host=self.host, port=self.api_port) if PlutoAPIClient else None
        self.telemetry_client = None
        self.video_client = None

    # -- connection lifecycle -------------------------------------------------
    def connect(self):
        """
        Verifies Pluto's FastAPI server is reachable, then starts the
        telemetry and camera WebSocket clients. Returns True only if the
        REST health check succeeds; the WS clients keep retrying in the
        background regardless (they'll pick up automatically once Pluto is
        actually online), so this call never blocks on them.
        """
        if self.api is None:
            return False

        try:
            self.connected = self.api.health_check()
        except PlutoAPIClientError:
            self.connected = False

        if PlutoWebSocketClient and self.telemetry_client is None:
            self.telemetry_client = PlutoWebSocketClient(
                host=self.host, port=self.ws_port, endpoint=TELEMETRY_ENDPOINT,
                on_message=self._on_telemetry_message,
                on_connect=lambda: setattr(self, "connected", True),
                on_disconnect=self._on_telemetry_disconnect,
            )
            self.telemetry_client.start()

        if PlutoVideoClient and self.video_client is None:
            self.video_client = PlutoVideoClient(
                host=self.host, port=self.ws_port, endpoint=CAMERA_ENDPOINT,
                on_frame=self._on_video_frame,
            )
            self.video_client.start()

        return self.connected

    def disconnect(self):
        if self.telemetry_client:
            self.telemetry_client.stop()
        if self.video_client:
            self.video_client.stop()
        if self.api:
            self.api.close()
        self.connected = False
        with self._telemetry_lock:
            self._telemetry = dict(self._EMPTY_TELEMETRY)
        with self._frame_lock:
            self._latest_frame = None

    # -- WebSocket callbacks (run on background threads) ---------------------
    def _on_telemetry_message(self, data: dict):
        """
        telemetry.py (Pi side) sends: cpu_percent, ram_percent, ram_used_mb,
        ram_total_mb, disk_percent, temperature_c, battery_percent,
        battery_charging, uptime_seconds.

        RobotCore's getters (below) were written against different key
        names (memory_percent, cpu_temp_c, connectivity, current_activity)
        and against environment-sensor fields telemetry.py doesn't send at
        all (those live in STM's sensor rows, pushed separately over
        websocket_server.py's /ws/live -- not this channel). Translate here
        so the rest of RobotCore doesn't need to change.
        """
        translated = {
            "cpu_percent": data.get("cpu_percent"),
            "memory_percent": data.get("ram_percent"),
            "cpu_temp_c": data.get("temperature_c"),
            "battery_percent": data.get("battery_percent"),
            "connectivity": {
                "type": "Connected", "state": "Online", "kind": "good",
            },
            "current_activity": data.get("current_activity", "Idle"),
        }
        with self._telemetry_lock:
            self._telemetry.update(translated)

    def _on_telemetry_disconnect(self):
        self.connected = False
        with self._telemetry_lock:
            self._telemetry["connectivity"] = {
                "type": "Offline", "state": "No Signal", "kind": "bad",
            }

    def _on_video_frame(self, image):
        with self._frame_lock:
            self._latest_frame = image

    def get_latest_frame(self):
        """Returns the most recent camera frame (PIL.Image) or None."""
        with self._frame_lock:
            return self._latest_frame

    # -- telemetry getters (read from the cached WebSocket snapshot) ---------
    def _snapshot(self):
        with self._telemetry_lock:
            return dict(self._telemetry)

    def get_battery_percent(self):
        val = self._snapshot().get("battery_percent")
        return val if val is not None else 0

    def get_connectivity(self):
        c = self._snapshot().get("connectivity") or self._EMPTY_TELEMETRY["connectivity"]
        return c.get("type", "Offline"), c.get("state", "No Signal"), c.get("kind", "bad")

    def get_memory_percent(self):
        val = self._snapshot().get("memory_percent")
        return val if val is not None else 0

    def get_cpu_percent(self):
        val = self._snapshot().get("cpu_percent")
        return val if val is not None else 0

    def get_cpu_temp_c(self):
        val = self._snapshot().get("cpu_temp_c")
        return val if val is not None else 0

    # -- environment / surrounding sensors -----------------------------------
    def get_ambient_temperature_c(self):
        val = self._snapshot().get("ambient_temperature_c")
        return val if val is not None else "--"

    def get_humidity_percent(self):
        val = self._snapshot().get("humidity_percent")
        return val if val is not None else "--"

    def get_light_intensity_lux(self):
        val = self._snapshot().get("light_intensity_lux")
        return val if val is not None else "--"

    def get_air_quality_index(self):
        val = self._snapshot().get("air_quality_index")
        return val if val is not None else 0

    def get_live_feed_status(self):
        return bool(self.video_client and self.video_client.is_connected())

    def get_current_activity(self):
        return self._snapshot().get("current_activity") or "Disconnected"

    # -- MEMORY CORE ----------------------------------------------------------
    # Four memory subsystems, read live from Pluto over the FastAPI
    # /memory/{type}/summary endpoint (see api_client.get_memory_summary).
    def get_memory_core_data(self):
        types = ("short_term", "semantic", "behavioral", "episodic")
        result = {}
        for t in types:
            if not self.api:
                result[t] = dict(self._EMPTY_MEMORY_CARD)
                continue
            try:
                result[t] = self.api.get_memory_summary(t)
            except PlutoAPIClientError:
                result[t] = dict(self._EMPTY_MEMORY_CARD)
        return result

    def register_owner(self, owner_data):
        """
        Sends the owner's face/voice samples to Pluto for enrollment via
        the FastAPI server (owner_manager.py). Returns True on success,
        False (and leaves the caller to inspect self.last_error) otherwise.

        server.py's /owners/register endpoint (owner_manager.py) requires
        AT LEAST ONE face file AND one voice file in the SAME call -- so
        both must be captured before this is invoked (see save_owner()'s
        validation in OwnerRegistrationFrame).
        """
        if not self.api:
            self.last_error = "API client unavailable (install 'requests')."
            return False

        name = owner_data.get("name", "owner")

        if not (owner_data.get("face_captured") and owner_data.get("face_path")):
            self.last_error = "A face capture is required to register an owner."
            return False
        if not (owner_data.get("voice_captured") and owner_data.get("voice_path")):
            self.last_error = "A voice sample is required to register an owner."
            return False

        # owner_manager.py validates dob strictly as 'YYYY-MM-DD'; the GUI's
        # date pickers build 'DD-MM-YYYY', so convert before sending.
        dob = _to_iso_dob(owner_data.get("dob", ""))

        try:
            self.api.register_owner(
                owner_name=name,
                dob=dob,
                face_paths=[owner_data["face_path"]],
                voice_paths=[owner_data["voice_path"]],
            )
            self.last_error = None
            return True
        except PlutoAPIClientError as e:
            self.last_error = str(e)
            return False


