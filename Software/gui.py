class MonitorCard(RoundedCard):
    """Displays what Pluto is currently 'seeing'. When connected and frames
    are arriving from video_client.py, renders the real camera stream;
    otherwise falls back to a 'NO SIGNAL' placeholder."""

    def __init__(self, parent, robot: "RobotCore" = None):
        super().__init__(parent)
        self.robot = robot
        self._frame_photo = None  # keep a reference so Tk doesn't GC it

        header = tk.Frame(self.body, bg=Theme.CARD)
        header.pack(
            fill="x",
            padx=12,
            pady=(6,2)
        )
        tk.Label(header, text="MONITOR", font=(Theme.FONT, 9, "bold"), bg=Theme.CARD,
                 fg=Theme.TEXT_SUB).pack(side="left")
        self.status_dot = tk.Canvas(header, width=9, height=9, bg=Theme.CARD,
                                     highlightthickness=0)
        self.status_dot.pack(side="right")
        self.status_dot.create_oval(1, 1, 8, 8, fill=Theme.BAD, outline="", tags="dot")
        self.status_label = tk.Label(header, text="SIMULATION FEED", font=(Theme.FONT, 8, "bold"),
                                      bg=Theme.CARD, fg=Theme.WARN)
        self.status_label.pack(side="right", padx=(0, 6))

        screen_wrap = tk.Frame(self.body, bg=Theme.CARD)
        screen_wrap.pack(
            fill="both",
            expand=True,
            padx=12,
            pady=(4,8)
        )
        self.screen = tk.Canvas(screen_wrap, bg="#05070b", highlightthickness=1,
                                 highlightbackground=Theme.BORDER)
        self.screen.pack(fill="both", expand=True)
        self.screen.bind("<Configure>", lambda e: self._draw_frame())

        self._tick = 0
        self.set_connected(False)
        self._animate()

    def set_connected(self, connected):
        color = Theme.GOOD if connected else Theme.BAD
        text = "LIVE" if connected else "SIMULATION FEED"
        self.status_dot.itemconfig("dot", fill=color)
        self.status_label.config(text=text, fg=(Theme.GOOD if connected else Theme.WARN))
        self._connected = connected

    def _draw_frame(self):
        """Render either the real camera frame (if video_client.py has one)
        or a 'NO SIGNAL' placeholder, with a CCTV-style OSD overlay
        (cam id, blinking REC dot, timestamp) drawn on top either way."""
        c = self.screen
        w = c.winfo_width()
        h = c.winfo_height()
        if w < 10 or h < 10:
            return
        c.delete("all")

        frame = self.robot.get_latest_frame() if self.robot else None

        if frame is not None and ImageTk is not None:
            # Fit the real frame to the canvas while preserving aspect ratio.
            fw, fh = frame.size
            scale = min(w / fw, h / fh)
            new_size = (max(1, int(fw * scale)), max(1, int(fh * scale)))
            resized = frame.resize(new_size)
            self._frame_photo = ImageTk.PhotoImage(resized)
            c.create_rectangle(0, 0, w, h, fill="#000000", outline="")
            c.create_image(w // 2, h // 2, image=self._frame_photo, anchor="center")
        else:
            # base picture area
            c.create_rectangle(0, 0, w, h, fill="#0b0f14", outline="")
            # faint horizontal scanlines -> analog-camera / CRT texture
            for y in range(0, h, 3):
                c.create_line(0, y, w, y, fill="#10151c")
            # light static/noise speckle, like a camera with no real signal yet
            for _ in range(90):
                x = random.randint(0, w)
                y = random.randint(0, h)
                sz = random.choice([1, 1, 2])
                shade = random.choice(["#1b222c", "#222a35", "#171d25"])
                c.create_rectangle(x, y, x + sz, y + sz, fill=shade, outline="")

        # thin vignette frame to sell a lens edge
        c.create_rectangle(0, 0, w, h, outline="#000000", width=3)

        # -- on-screen camera overlay (like a real CCTV OSD) -----------------
        c.create_text(12, 12, anchor="nw", text="CAM-01  \u2022  PLUTO",
                      fill=Theme.ACCENT, font=(Theme.FONT, 9, "bold"))

        if frame is not None and self._tick % 20 < 12:  # blinking REC indicator
            c.create_oval(w - 22, 12, w - 12, 22, fill=Theme.BAD, outline="")
            c.create_text(w - 28, 17, anchor="e", text="REC",
                          fill=Theme.BAD, font=(Theme.FONT, 9, "bold"))

        timestamp = datetime.datetime.now().strftime("%d-%m-%Y  %H:%M:%S")
        c.create_text(12, h - 12, anchor="sw", text=timestamp,
                      fill="#c7cfd8", font=("Consolas", 9))

        if frame is None:
            cx, cy = w / 2, h / 2
            c.create_text(cx, cy - 10, text="\U0001F4F9", font=(Theme.FONT, 26))
            c.create_text(cx, cy + 20, text="NO SIGNAL",
                          fill=Theme.TEXT_SUB, font=(Theme.FONT, 10, "bold"))
            c.create_text(cx, cy + 40, text="Connect to Pluto Core to view the live camera",
                          fill=Theme.TEXT_FAINT, font=(Theme.FONT, 8))

    def _animate(self):
        self._tick += 1
        self._draw_frame()
        self.after(150, self._animate)


