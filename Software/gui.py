        self.robot = robot

        # -- top strip: compact status boxes (Battery / Connectivity / --------
        # -- Memory / CPU) --------------------------------------------------
        strip = tk.Frame(self, bg=Theme.BG)
        strip.pack(fill="x", padx=28, pady=(10, 4))
        for i in range(4):
            strip.columnconfigure(i, weight=1, uniform="ministats")

